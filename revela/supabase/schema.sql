create table public.payment_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  status text not null default 'requested' check (status in ('requested','reported','verified','cancelled')),
  reference text,
  requested_at timestamptz not null default now(),
  reported_at timestamptz,
  verified_at timestamptz,
  verified_by uuid references auth.users(id)
);
create table public.admin_audit (
  id bigint generated always as identity primary key,
  actor_id uuid not null references auth.users(id),
  subject_id uuid references auth.users(id),
  action text not null,
  detail text,
  created_at timestamptz not null default now()
);
create table public.resources (
  id uuid primary key default gen_random_uuid(),
  module_id integer not null references public.modules(id),
  title text not null,
  storage_path text not null unique,
  created_at timestamptz not null default now()
);
create table public.submissions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  module_id integer not null references public.modules(id),
  files jsonb not null,
  reflection text not null,
  status text not null default 'pending' check (status in ('pending','accepted','rejected')),
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users(id),
  review_note text
);
create index submissions_user_module_idx on public.submissions(user_id,module_id,submitted_at desc);
create table public.quiz_questions (
  id bigint generated by default as identity primary key,
  module_id integer not null references public.modules(id),
  position integer not null,
  prompt text not null,
  options jsonb not null check (jsonb_typeof(options)='array' and jsonb_array_length(options)=4),
  unique(module_id,position)
);
create table private.quiz_keys (
  question_id bigint primary key references public.quiz_questions(id) on delete cascade,
  correct_index integer not null check (correct_index between 0 and 3)
);
create table public.quiz_attempts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  module_id integer not null references public.modules(id),
  answers jsonb not null,
  correct_count integer not null default 0,
  question_count integer not null default 0,
  passed boolean not null default false,
  submitted_at timestamptz not null default now()
);
create index quiz_attempts_user_module_idx on public.quiz_attempts(user_id,module_id,submitted_at desc);

create function private.sync_profile() returns trigger language plpgsql security definer set search_path='' as $$
begin
  insert into public.profiles(user_id,email,full_name)
  values (new.id,coalesce(new.email,''),left(coalesce(new.raw_user_meta_data->>'full_name',''),100))
  on conflict (user_id) do update set email=excluded.email,full_name=excluded.full_name;
  return new;
end; $$;
create trigger sync_revela_profile after insert or update of email,raw_user_meta_data on auth.users
for each row execute function private.sync_profile();

create function private.is_admin() returns boolean language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.app_admins where user_id=(select auth.uid()));
$$;
create function private.has_access() returns boolean language sql stable security definer set search_path='' as $$
  select exists(select 1 from public.course_access where user_id=(select auth.uid()) and granted_at is not null and revoked_at is null);
$$;
create function public.my_role() returns boolean language sql stable set search_path='' as $$
  select private.is_admin();
$$;

-- Client-supplied grades are ignored. This trigger grades all questions in the database.
create function private.grade_attempt() returns trigger language plpgsql security definer set search_path='' as $$
declare v_total integer; v_correct integer; v_valid integer; v_keys integer;
begin
  if auth.uid() is null or new.user_id <> auth.uid() then raise exception 'Cuenta no válida'; end if;
  if not exists (select 1 from public.modules where id=new.module_id and (is_free or private.has_access() or private.is_admin())) then
    raise exception 'Módulo sin acceso';
  end if;
  if jsonb_typeof(new.answers) <> 'object' then raise exception 'Respuestas inválidas'; end if;
  select count(*) into v_keys from jsonb_object_keys(new.answers);
  select count(*),
    count(*) filter (where new.answers ? q.id::text and (new.answers->>q.id::text) ~ '^[0-3]$' and (new.answers->>q.id::text)::integer < jsonb_array_length(q.options)),
    count(*) filter (where new.answers ? q.id::text and (new.answers->>q.id::text) ~ '^[0-3]$' and (new.answers->>q.id::text)::integer = k.correct_index)
  into v_total,v_valid,v_correct
  from public.quiz_questions q join private.quiz_keys k on k.question_id=q.id where q.module_id=new.module_id;
  if v_total=0 or v_keys<>v_total or v_valid<>v_total then raise exception 'Completá todas las respuestas'; end if;
  new.correct_count := v_correct;
  new.question_count := v_total;
  new.passed := v_correct * 100 >= 85 * v_total;
  new.submitted_at := now();
  return new;
end; $$;
create trigger grade_revela_attempt before insert on public.quiz_attempts for each row execute function private.grade_attempt();

-- A file upload alone is not an accepted educational submission.
create function private.validate_submission() returns trigger language plpgsql security definer set search_path='' as $$
declare v_path text; v_count integer;
begin
  if auth.uid() is null or new.user_id <> auth.uid() then raise exception 'Cuenta no válida'; end if;
  if not exists (select 1 from public.modules where id=new.module_id and (is_free or private.has_access() or private.is_admin())) then
    raise exception 'Módulo sin acceso';
  end if;
  if jsonb_typeof(new.files)<>'array' then raise exception 'Archivos inválidos'; end if;
  v_count := jsonb_array_length(new.files);
  if v_count<>3 or length(trim(new.reflection))<30 or length(new.reflection)>1000 then
    raise exception 'La entrega requiere tres imágenes y una reflexión de 30 a 1000 caracteres';
  end if;
  if (select count(distinct item.path) from jsonb_array_elements_text(new.files) as item(path)) <> 3 then
    raise exception 'Elegí tres imágenes distintas';
  end if;
  for v_path in select jsonb_array_elements_text(new.files) loop
    if v_path not like auth.uid()::text || '/%' or not exists (
      select 1 from storage.objects where bucket_id='student-work' and name=v_path and owner_id=auth.uid()::text
    ) then raise exception 'Archivo no disponible para tu cuenta'; end if;
  end loop;
  new.status := 'pending';
  new.submitted_at := now();
  return new;
end; $$;
create trigger validate_revela_submission before insert on public.submissions for each row execute function private.validate_submission();

create function private.report_payment(p_reference text) returns void language plpgsql security definer set search_path='' as $$
begin
  if auth.uid() is null or not exists(select 1 from public.payment_settings where id=1 and payments_enabled) then raise exception 'Pagos no habilitados'; end if;
  if length(trim(coalesce(p_reference,'')))>140 then raise exception 'Referencia demasiado larga'; end if;
  update public.payment_requests set status='reported',reference=nullif(trim(p_reference),''),reported_at=now()
  where user_id=auth.uid() and status in ('requested','reported');
  if not found then raise exception 'Primero solicitá el acceso'; end if;
end; $$;
create function public.report_payment(p_reference text) returns void language sql set search_path='' as $$
  select private.report_payment(p_reference);
$$;

create function private.set_course_access(p_user uuid,p_grant boolean,p_note text) returns void language plpgsql security definer set search_path='' as $$
begin
  if not private.is_admin() then raise exception 'Acceso denegado'; end if;
  if p_user is null or length(coalesce(p_note,''))>500 then raise exception 'Datos inválidos'; end if;
  if p_grant then
    if not exists(select 1 from public.payment_requests where user_id=p_user and status in ('reported','verified')) then
      raise exception 'Falta aviso de transferencia de esta cuenta';
    end if;
    insert into public.course_access(user_id,granted_at,granted_by,note)
    values(p_user,now(),auth.uid(),p_note)
    on conflict(user_id) do update set granted_at=now(),revoked_at=null,granted_by=auth.uid(),note=p_note;
    update public.payment_requests set status='verified',verified_at=now(),verified_by=auth.uid() where user_id=p_user;
  else
    update public.course_access set revoked_at=now(),note=p_note where user_id=p_user and revoked_at is null;
    if not found then raise exception 'No hay acceso activo'; end if;
  end if;
  insert into public.admin_audit(actor_id,subject_id,action,detail)
  values(auth.uid(),p_user,case when p_grant then 'grant_access' else 'revoke_access' end,p_note);
end; $$;
create function public.set_course_access(p_user uuid,p_grant boolean,p_note text default null) returns void language sql set search_path='' as $$
  select private.set_course_access(p_user,p_grant,p_note);
$$;
create function private.review_submission(p_submission uuid,p_accept boolean,p_note text) returns void language plpgsql security definer set search_path='' as $$
declare v_user uuid;
begin
  if not private.is_admin() then raise exception 'Acceso denegado'; end if;
  if length(coalesce(p_note,''))>1000 then raise exception 'Comentario demasiado largo'; end if;
  update public.submissions set status=case when p_accept then 'accepted' else 'rejected' end,
    review_note=nullif(trim(p_note),''),reviewed_by=auth.uid(),reviewed_at=now()
  where id=p_submission and status='pending' returning user_id into v_user;
  if not found then raise exception 'La entrega ya fue revisada o no existe'; end if;
  insert into public.admin_audit(actor_id,subject_id,action,detail)
  values(auth.uid(),v_user,case when p_accept then 'accept_submission' else 'reject_submission' end,p_submission::text);
end; $$;
create function public.review_submission(p_submission uuid,p_accept boolean,p_note text default null) returns void language sql set search_path='' as $$
  select private.review_submission(p_submission,p_accept,p_note);
$$;

